def write_png(path, pixels, size):
    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in pixels)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, rows in ART.items():
        palette = PALETTES[name]
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), f"{name}: art must be 16x16"
        pixels = []
        for row in rows:
            # Each art cell becomes a 2x2 block: 16x16 art -> 32x32 sprite.
            line = []
            for ch in row:
                rgba = palette[ch] + (255,) if ch in palette else (245, 240, 230, 255) if ch == "9" else (0, 0, 0, 0)
                line += [rgba, rgba]
            pixels += [line, line]
        out = OUT.parent / "trinkets" if name in TRINKETS else OUT
        out.mkdir(parents=True, exist_ok=True)
        write_png(out / f"{name}.png", pixels, 32)
        print(f"wrote {out / (name + '.png')}")


if __name__ == "__main__":
    main()
